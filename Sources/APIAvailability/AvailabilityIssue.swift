import Foundation

public enum APIAvailabilityError: LocalizedError, Equatable {
    case sdkNotFound(ApplePlatform)
    case invalidVersion(String)
    case unknownPlatform(String)
    case fileNotFound(String)
    case toolFailed(String, String)

    public var errorDescription: String? {
        switch self {
        case .sdkNotFound(let platform):
            return "No \(platform.rawValue) SDK found. Install Xcode and select it with `xcode-select`."
        case .invalidVersion(let version):
            return "'\(version)' is not a version number (expected e.g. \"15\" or \"16.4\")."
        case .unknownPlatform(let name):
            return "Unknown platform '\(name)'. Use iOS, macOS, tvOS, watchOS or visionOS."
        case .fileNotFound(let path):
            return "File not found: \(path)"
        case .toolFailed(let tool, let message):
            return "Failed to run \(tool): \(message)"
        }
    }
}

/// One use of an API that the deployment target cannot rely on.
public struct AvailabilityIssue: Equatable, Sendable {
    public enum Kind: Equatable, Sendable {
        /// Introduced in a newer OS than the deployment target.
        case requiresNewer(version: String)
        /// Deprecated at or before the deployment target.
        case deprecated(version: String?, message: String?)
        /// Removed (obsoleted) at or before the deployment target.
        case obsoleted(version: String)
        /// Not available on this platform at all.
        case unavailable(message: String?)
    }

    public let file: String
    public let line: Int
    public let column: Int
    public let symbol: String
    public let kind: Kind
    public let message: String
}

/// Turns `swiftc -diagnostic-style=llvm` output into availability issues.
enum AvailabilityDiagnosticParser {
    struct Result: Equatable {
        var issues: [AvailabilityIssue] = []
        /// Errors unrelated to availability; they can hide availability errors
        /// in the code they affect.
        var otherErrors: [String] = []
        /// Modules that could not be imported (e.g. package dependencies).
        var missingModules: [String] = []
    }

    private static let diagnosticLine = try! NSRegularExpression(
        pattern: #"^(.+?):(\d+):(\d+): (error|warning): (.*)$"#
    )
    private static let requiresNewer = try! NSRegularExpression(
        pattern: #"is only available in ([A-Za-z]+) ([\d.]+) or newer"#
    )
    private static let deprecated = try! NSRegularExpression(
        pattern: #"was deprecated in ([A-Za-z]+)(?: ([\d.]+))?(?:: (.*))?$"#
    )
    private static let obsoleted = try! NSRegularExpression(
        pattern: #"was obsoleted in ([A-Za-z]+) ([\d.]+)"#
    )
    private static let unavailable = try! NSRegularExpression(
        pattern: #"is unavailable in ([A-Za-z]+)(?:: (.*))?$"#
    )
    private static let missingModule = try! NSRegularExpression(
        pattern: #"no such module '([^']+)'"#
    )
    private static let moduleDeploymentTarget = try! NSRegularExpression(
        pattern:
            #"compiling for ([A-Za-z]+) [\d.]+, but module '([^']+)' has a minimum deployment target of ([A-Za-z]+) ([\d.]+)"#
    )

    static func parse(_ output: String, platform: ApplePlatform) -> Result {
        var result = Result()
        var seen = Set<String>()

        for rawLine in output.split(whereSeparator: \.isNewline) {
            let line = String(rawLine)
            guard let match = firstMatch(diagnosticLine, in: line) else {
                continue
            }

            let path = match[1]
            // Code generated by macro expansion is reported again at the macro's
            // use site in the real file, so the generated copies are noise.
            if path.contains("swift-generated-sources") || path.contains("@__swiftmacro_")
                || path.hasPrefix("macro expansion")
            {
                continue
            }

            let severity = match[4]
            var message = stripDiagnosticGroup(match[5])
            var kind = availabilityKind(of: message, platform: platform)

            // A dependency built for a newer OS than the deployment target.
            if kind == nil, let module = firstMatch(moduleDeploymentTarget, in: message),
                module[1] == platform.availabilityName
            {
                kind = .requiresNewer(version: module[4])
                message = "'import \(module[2])' module requires \(module[3]) \(module[4])"
            }

            guard let kind else {
                if severity == "error" {
                    if let module = firstMatch(missingModule, in: message)?[1] {
                        if !result.missingModules.contains(module) {
                            result.missingModules.append(module)
                        }
                    } else {
                        result.otherErrors.append("\(path):\(match[2]):\(match[3]): \(message)")
                    }
                }
                continue
            }

            let key = "\(path):\(match[2]):\(match[3]):\(message)"
            guard seen.insert(key).inserted else {
                continue
            }

            result.issues.append(
                AvailabilityIssue(
                    file: path,
                    line: Int(match[2]) ?? 0,
                    column: Int(match[3]) ?? 0,
                    symbol: quotedSymbol(in: message),
                    kind: kind,
                    message: message
                )
            )
        }

        return result
    }

    private static func availabilityKind(of message: String, platform: ApplePlatform) -> AvailabilityIssue.Kind? {
        let name = platform.availabilityName

        if let match = firstMatch(requiresNewer, in: message), match[1] == name {
            return .requiresNewer(version: match[2])
        }
        if let match = firstMatch(deprecated, in: message), match[1] == name {
            return .deprecated(version: match[2].isEmpty ? nil : match[2], message: match[3].isEmpty ? nil : match[3])
        }
        if let match = firstMatch(obsoleted, in: message), match[1] == name {
            return .obsoleted(version: match[2])
        }
        if let match = firstMatch(unavailable, in: message), match[1] == name {
            return .unavailable(message: match[2].isEmpty ? nil : match[2])
        }
        return nil
    }

    /// Drops a trailing diagnostic group tag such as " [#DeprecatedDeclaration]".
    private static func stripDiagnosticGroup(_ message: String) -> String {
        guard message.hasSuffix("]"), let range = message.range(of: " [#", options: .backwards) else {
            return message
        }
        return String(message[..<range.lowerBound])
    }

    private static func quotedSymbol(in message: String) -> String {
        guard let start = message.firstIndex(of: "'"),
            let end = message[message.index(after: start)...].firstIndex(of: "'")
        else {
            return message
        }
        return String(message[message.index(after: start)..<end])
    }

    /// Capture groups of the first match; groups that did not participate are "".
    private static func firstMatch(_ regex: NSRegularExpression, in text: String) -> [String]? {
        let range = NSRange(text.startIndex..., in: text)
        guard let match = regex.firstMatch(in: text, range: range) else {
            return nil
        }
        return (0..<match.numberOfRanges).map { index in
            Range(match.range(at: index), in: text).map { String(text[$0]) } ?? ""
        }
    }
}
